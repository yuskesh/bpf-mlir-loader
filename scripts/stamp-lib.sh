
BML_STAMP_NL=$(printf '\n.')
BML_STAMP_NL=${BML_STAMP_NL%.}
BML_STAMP_TAB=$(printf '\t')

bml_stamp_fail() {
  echo "stamp-facts: $*" >&2
  return 1
}

bml_stamp_hex() {
  if [ "${BML_STAMP_MUT:-}" = lenient_hex ]; then
    [[ $1 =~ ^[0-9a-f]+$ ]]
  else
    [[ $1 =~ ^[0-9a-f]{40}$ ]]
  fi
}

bml_stamp_read() {
  local all kept
  all=$(wc -c < "$1") || return 1
  kept=$(tr -d '\000' < "$1" | wc -c) || return 1
  [ "$all" = "$kept" ] || bml_stamp_fail "$1 contains a NUL byte" || return 1
  cat -- "$1" || return 1
  printf x
}

bml_stamp_owned() {
  local top real
  if [ "${BML_STAMP_MUT:-}" = no_owner_check ]; then
    git -C "$1" rev-parse --git-dir > /dev/null 2>&1
    return
  fi
  if [ ! -e "$1/.git" ] && [ ! -L "$1/.git" ]; then return 1; fi
  top=$(git -C "$1" rev-parse --show-toplevel 2> /dev/null) || return 2
  real=$(cd -- "$1" && pwd -P) || return 2
  [ "$top" = "$real" ] || return 2
}

bml_stamp_owned_or_stop() {
  local rc=0
  bml_stamp_owned "$1" || rc=$?
  case $rc in
    0) echo yes ;;
    1) echo no ;;
    *) bml_stamp_fail "git cannot read the repository at $1" || return 1 ;;
  esac
}

bml_stamp_dirty() {
  local st
  if [ "${BML_STAMP_MUT:-}" = plain_status ]; then
    st=$(git -C "$1" status --porcelain) || bml_stamp_fail "git status failed in $1" || return 1
  else
    st=$(git -C "$1" status --porcelain --untracked-files=normal --ignore-submodules=none) ||
      bml_stamp_fail "git status failed in $1" || return 1
  fi
  if [ -n "$st" ]; then echo 1; else echo 0; fi
}

bml_stamp_facts() {
  local t="$1" c form source dirty bpf row hex='[0-9a-f]{40}' n="$BML_STAMP_NL"
  local re_sv re_pins re_link
  [ -d "$t" ] || bml_stamp_fail "not a directory: $t" || return 1
  if [ "${BML_STAMP_MUT:-}" = lenient_hex ]; then hex='[0-9a-f]+'; fi
  re_sv="^format=1${n}version=[0-9]+\\.[0-9]+\\.[0-9]+${n}source_commit=(${hex})${n}\$"
  re_pins="^format=1${n}bpf_mlir_source_commit=([0-9a-f]{40})${n}\$"
  re_link="^160000 commit ([0-9a-f]+)${BML_STAMP_TAB}third_party/bpf-mlir\$"
  local owned
  owned=$(bml_stamp_owned_or_stop "$t") || return 1
  if [ -e "$t/SOURCE_VERSION" ] || [ -L "$t/SOURCE_VERSION" ]; then
    form=public
    c=$(bml_stamp_read "$t/SOURCE_VERSION") || bml_stamp_fail "cannot read $t/SOURCE_VERSION" || return 1
    c=${c%x}
    [[ $c =~ $re_sv ]] ||
      bml_stamp_fail "SOURCE_VERSION is not format=1, version=<n.n.n>, source_commit=<40 hex>" || return 1
    source=${BASH_REMATCH[1]}
    [ -e "$t/PINS" ] || [ -L "$t/PINS" ] || bml_stamp_fail "SOURCE_VERSION without PINS in $t" || return 1
    c=$(bml_stamp_read "$t/PINS") || bml_stamp_fail "cannot read $t/PINS" || return 1
    c=${c%x}
    [[ $c =~ $re_pins ]] ||
      bml_stamp_fail "PINS is not exactly format=1, bpf_mlir_source_commit=<40 hex>" || return 1
    bpf=${BASH_REMATCH[1]}
    if [ "$owned" = yes ]; then
      dirty=$(bml_stamp_dirty "$t") || return 1
    else
      dirty=-1
    fi
  elif [ "$owned" = yes ]; then
    form=dev
    source=$(git -C "$t" rev-parse HEAD) || bml_stamp_fail "git rev-parse HEAD failed in $t" || return 1
    if [ "${BML_STAMP_MUT:-}" = nested_rev_parse ]; then
      bpf=$(git -C "$t/third_party/bpf-mlir" rev-parse HEAD) || bml_stamp_fail "nested rev-parse failed" || return 1
    else
      row=$(git -C "$t" ls-tree HEAD third_party/bpf-mlir) || bml_stamp_fail "git ls-tree HEAD failed in $t" || return 1
      [[ $row =~ $re_link ]] ||
        bml_stamp_fail "HEAD has no third_party/bpf-mlir gitlink in $t" || return 1
      bpf=${BASH_REMATCH[1]}
    fi
    dirty=$(bml_stamp_dirty "$t") || return 1
  else
    printf 'form=none\nsource_commit=unknown\ndirty=-1\nbpf_mlir_commit=unknown\n'
    return 0
  fi
  bml_stamp_hex "$source" || bml_stamp_fail "source commit is not 40 lowercase hex: $source" || return 1
  bml_stamp_hex "$bpf" || bml_stamp_fail "bpf-mlir commit is not 40 lowercase hex: $bpf" || return 1
  printf 'form=%s\nsource_commit=%s\ndirty=%s\nbpf_mlir_commit=%s\n' "$form" "$source" "$dirty" "$bpf"
}

bml_stamp_header() {
  local form source dirty bpf line
  while IFS= read -r line; do
    case "$line" in
      form=*) form=${line#form=} ;;
      source_commit=*) source=${line#source_commit=} ;;
      dirty=*) dirty=${line#dirty=} ;;
      bpf_mlir_commit=*) bpf=${line#bpf_mlir_commit=} ;;
    esac
  done <<< "$1"
  printf '/* generated by scripts/stamp-lib.sh (build-libs.sh) — the version facts of this build */\n'
  printf '#define BML_STAMP_FORM "%s"\n#define BML_STAMP_SOURCE_COMMIT "%s"\n' "$form" "$source"
  printf '#define BML_STAMP_DIRTY %s\n#define BML_STAMP_BPF_MLIR_COMMIT "%s"\n' "$dirty" "$bpf"
}

bml_stamp_guarded() {
  local t="$1" d="$2" f1 f2 rc=0 err had_e=0
  shift 2
  case $- in *e*) had_e=1 ;; esac
  mkdir -p "$d" || return 1
  err="$d/bml_stamp.err"
  f1=$(bml_stamp_facts "$t" 2> "$err") || {
    echo "build-libs: cannot read the source facts before the build: $(cat "$err")" >&2
    return 1
  }
  bml_stamp_header "$f1" > "$d/bml_stamp.h" || return 1
  set +e
  (
    set -e
    "$@"
  )
  rc=$?
  if [ "$had_e" = 1 ]; then set -e; fi
  [ "$rc" = 0 ] || return "$rc"
  case "${BML_STAMP_MUT:-}" in
    skip_second_read) return 0 ;;
    ignore_second_read)
      bml_stamp_facts "$t" > /dev/null 2>&1 || :
      return 0
      ;;
  esac
  f2=$(bml_stamp_facts "$t" 2> "$err") || {
    echo "build-libs: cannot read the source facts after the build: $(cat "$err")" >&2
    return 1
  }
  if [ "$f1" != "$f2" ]; then
    echo "build-libs: the source facts changed during the build" >&2
    return 1
  fi
  rm -f "$err"
}
