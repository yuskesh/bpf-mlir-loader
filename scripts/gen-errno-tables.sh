#!/bin/bash
# scripts/gen-errno-tables.sh — the errno tables: write src/util/errno_tables.h from the two committed canonical inputs
# (src/util/kernel_errno.tsv and go_errno.tsv, made by scripts/gen-errno-inputs.sh). Shell and awk only: no Go and no
# kernel tree, so a clean checkout reproduces it.
#
#   scripts/gen-errno-tables.sh [ROOT]           # write ROOT/src/util/errno_tables.h (ROOT defaults to the repo)
#   scripts/gen-errno-tables.sh --check [ROOT]   # the gate: regenerate and compare byte for byte with the committed header
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
check=0
[ "${1:-}" = --check ] && { check=1; shift; }
ROOT="${1:-$HERE}"
K="$ROOT/src/util/kernel_errno.tsv"
G="$ROOT/src/util/go_errno.tsv"
H="$ROOT/src/util/errno_tables.h"
die() { echo "gen-errno-tables: $*" >&2; exit 1; }
[ -f "$K" ] && [ -f "$G" ] || die "missing $K or $G"
# Every data row is <number>\t<text> with a number and a text that needs no C escape; anything else stops the generator.
for f in "$K" "$G"; do
  bad=$(awk -F'\t' '!/^#/ && (NF != 2 || $1 !~ /^[0-9]+$/ || $2 == "" || $2 ~ /["\\]/) { print FILENAME ":" NR; exit }' "$f")
  [ -z "$bad" ] || die "a malformed row at $bad"
done
awk -F'\t' '!/^#/ && $2 !~ /^E[A-Z0-9_]+$/ { exit 1 }' "$K" || die "$K: a name is not E[A-Z0-9_]+"
gen() {
  echo "/* errno_tables.h — generated by scripts/gen-errno-tables.sh from src/util/kernel_errno.tsv and src/util/go_errno.tsv"
  echo " * (kernel source trees and Go's source); do not edit. The inputs name their sources:"
  awk -F'\t' '/^# source\t/ { printf " *   kernel: linux %s, include/linux/errno.h sha256 %s\n", $3, $4 }' "$K"
  awk -F'\t' '/^# source\t/ { printf " *   Go: %s %s, sha256 %s\n", $3, $2, $4 }' "$G"
  echo " */"
  echo "#ifndef BML_UTIL_ERRNO_TABLES_H"
  echo "#define BML_UTIL_ERRNO_TABLES_H"
  echo ""
  echo "/* The kernel-internal errnos (include/linux/errno.h), ascending. */"
  echo "static const struct { int n; const char *name; } bml_kernel_errnos[] = {"
  awk -F'\t' '!/^#/ { printf "\t{%s, \"%s\"},\n", $1, $2 }' "$K"
  echo "};"
  echo ""
  echo "/* Go's syscall.Errno texts (the errors array); a NULL entry, and any number past the end, is \"errno N\". */"
  echo "static const char *const bml_go_errnos[] = {"
  awk -F'\t' '!/^#/ { printf "\t[%s] = \"%s\",\n", $1, $2 }' "$G"
  echo "};"
  echo ""
  echo "#endif"
}
# Generate once into a temporary file, as a plain statement: under set -eE the ERR trap stops a failure at any line
# of gen (in "gen > f || die" bash would ignore set -e inside gen). A comparison with <(gen) cannot see gen's status.
T="$(mktemp "${TMPDIR:-/tmp}/errno_tables.XXXXXX")"
trap 'rm -f "$T"' EXIT
set -E
trap 'echo "gen-errno-tables: the header generator failed" >&2' ERR
gen > "$T"
trap - ERR
if [ "$check" = 1 ]; then
  [ -f "$H" ] || die "no $H"
  cmp -s "$T" "$H" || { { diff "$H" "$T" || true; } | awk 'NR <= 5' >&2; die "$H differs from its inputs (regenerate with scripts/gen-errno-tables.sh)"; }
  echo "gen-errno-tables: errno_tables.h equals its inputs ($(grep -vc '^#' "$K") kernel names, $(grep -vc '^#' "$G") Go texts)"
else
  chmod 644 "$T" && mv "$T" "$H"
fi
